package io.openems.edge.notification.email;

import org.osgi.service.metatype.annotations.AttributeDefinition;
import org.osgi.service.metatype.annotations.ObjectClassDefinition;

@ObjectClassDefinition(name = "Edge Email Notification", description = "Queues email notifications for configured recipients")
@interface Config {
	@AttributeDefinition(name = "Component-ID")
	String id() default "email0";

	@AttributeDefinition(name = "Alias")
	String alias() default "";

	@AttributeDefinition(name = "Enabled")
	boolean enabled() default true;

	@AttributeDefinition(name = "Email Sender-ID", description = "Component-ID of the Email Sender")
	String sender_id() default "emailSender0";

	@AttributeDefinition(name = "To")
	String[] to();

	@AttributeDefinition(name = "Cc")
	String[] cc() default {};

	@AttributeDefinition(name = "Queue Capacity")
	int queueCapacity() default 1_000;

	@AttributeDefinition(name = "Maximum Attempts")
	int maxAttempts() default 5;

	@AttributeDefinition(name = "Email Sender target filter", description = "This is auto-generated by 'Email Sender-ID'.")
	String sender_target() default "(enabled=true)";

	String webconsole_configurationFactory_nameHint() default "Edge Email Notification [{id}]";
}
