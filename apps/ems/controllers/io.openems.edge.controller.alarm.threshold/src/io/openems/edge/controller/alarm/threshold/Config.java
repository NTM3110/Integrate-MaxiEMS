package io.openems.edge.controller.alarm.threshold;

import org.osgi.service.metatype.annotations.AttributeDefinition;
import org.osgi.service.metatype.annotations.ObjectClassDefinition;

@ObjectClassDefinition(name = "Controller Wika Alarm", description = "Monitors Wika AMS01 alarm channels and queues email notifications")
@interface Config {
	@AttributeDefinition(name = "Component-ID")
	String id() default "ctrlWikaAlarm0";

	@AttributeDefinition(name = "Alias")
	String alias() default "";

	@AttributeDefinition(name = "Enabled")
	boolean enabled() default true;

	@AttributeDefinition(name = "Plant Name")
	String plantName();

	@AttributeDefinition(name = "Email Notification-ID", description = "Component-ID of the Email Notification")
	String email_id() default "email0";

	@AttributeDefinition(name = "Debounce [s]")
	int debounceSeconds() default 10;

	@AttributeDefinition(name = "Email Batch Window [s]")
	int batchWindowSeconds() default 10;

	@AttributeDefinition(name = "Email Notification target filter", description = "This is auto-generated by 'Email Notification-ID'.")
	String emailService_target() default "(enabled=true)";

	String webconsole_configurationFactory_nameHint() default "Controller Wika Alarm [{id}]";
}
