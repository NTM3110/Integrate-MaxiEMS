package io.openems.edge.pvinverter.solaredge;

import org.osgi.service.metatype.annotations.AttributeDefinition;
import org.osgi.service.metatype.annotations.ObjectClassDefinition;

@ObjectClassDefinition(//
		name = "PV-Inverter Solar Edge Modbus", //
		description = "")
@interface Config {

	@AttributeDefinition(name = "Component-ID", description = "Unique ID of this Component")
	String id() default "pvinverter0";

	@AttributeDefinition(name = "Alias", description = "Human-readable name of this Component; defaults to Component-ID")
	String alias() default "";

	@AttributeDefinition(name = "Is enabled?", description = "Is this Component enabled?")
	boolean enabled() default true;

	@AttributeDefinition(name = "Modbus-ID", description = "ID of Modbus bridge.")
	String modbus_id() default "modbus0";

	@AttributeDefinition(name = "Modbus Unit-ID", description = "The Unit-ID of the Modbus device.")
	int modbusUnitId() default 1;
	
	@AttributeDefinition(name = "Maximum Active Power", description = "This is the rated output of the PV installation.")
	int maxActivePower();
	
	@AttributeDefinition(name = "Inverter Model", description = "The model of the Inverter (affects Meter addresses).")
	InverterModel inverterModel() default InverterModel.DEFAULT;

	@AttributeDefinition(name = "Enable Meter 1", description = "Enable reading from Meter 1")
	boolean enableMeter1() default false;
	
	@AttributeDefinition(name = "Enable Meter 2", description = "Enable reading from Meter 2")
	boolean enableMeter2() default false;
	
	@AttributeDefinition(name = "Enable Meter 3", description = "Enable reading from Meter 3")
	boolean enableMeter3() default false;

	@AttributeDefinition(name = "Invert Meter Power", description = "Inverts all Power values of the auto-activated Meter")
	boolean invert_meter() default false;
	
	@AttributeDefinition(name = "Modbus target filter", description = "This is auto-generated by 'Modbus-ID'.")
	String Modbus_target() default "(enabled=true)";

	String webconsole_configurationFactory_nameHint() default "io.openems.edge.pvinverter.solaredge [{id}]";

}