#!/bin/bash
#
# OpenEMS Network Sudoers Setup Script
# 
# This script configures passwordless sudo access for network management commands
# Required for the io.openems.edge.network.manager bundle
#
# Usage: sudo ./setup-network-sudoers.sh [username]
#        Default username: openems
#

set -e

# Default username
OPENEMS_USER="${1:-openems}"
SUDOERS_FILE="/etc/sudoers.d/openems-network"
CHECKPOINT_HELPER="/usr/local/sbin/openems-network-checkpoint"

echo "=============================================="
echo "OpenEMS Network Sudoers Setup"
echo "=============================================="
echo ""

# Check if running as root
if [ "$EUID" -ne 0 ]; then
    echo "ERROR: This script must be run as root (use sudo)"
    exit 1
fi

# Check if user exists
if ! id "$OPENEMS_USER" &>/dev/null; then
    echo "WARNING: User '$OPENEMS_USER' does not exist."
    echo "         Creating user..."
    useradd -r -s /bin/false "$OPENEMS_USER" 2>/dev/null || true
fi

echo "Configuring sudo access for user: $OPENEMS_USER"
echo ""

cat > "$CHECKPOINT_HELPER" << 'HELPER'
#!/bin/bash
set -euo pipefail

ACTION="${1:-}"
VALUE="${2:-}"
TIMEOUT="${3:-}"

case "$ACTION" in
    create)
        if [[ "$VALUE" != "eth0" && "$VALUE" != "eth1" ]]; then
            exit 2
        fi
        if [[ ! "$TIMEOUT" =~ ^[1-9][0-9]{0,3}$ ]]; then
            exit 2
        fi
        DEVICE_PATH="$(/usr/bin/nmcli -g GENERAL.DBUS-PATH device show "$VALUE")"
        [[ "$DEVICE_PATH" =~ ^/org/freedesktop/NetworkManager/Devices/[0-9]+$ ]] || exit 3
        exec /usr/bin/busctl call org.freedesktop.NetworkManager /org/freedesktop/NetworkManager \
            org.freedesktop.NetworkManager CheckpointCreate aouu 1 "$DEVICE_PATH" "$TIMEOUT" 3
        ;;
    commit|rollback)
        [[ "$VALUE" =~ ^/org/freedesktop/NetworkManager/Checkpoint/[0-9]+$ ]] || exit 2
        if [[ "$ACTION" == "commit" ]]; then
            METHOD="CheckpointDestroy"
        else
            METHOD="CheckpointRollback"
        fi
        exec /usr/bin/busctl call org.freedesktop.NetworkManager /org/freedesktop/NetworkManager \
            org.freedesktop.NetworkManager "$METHOD" o "$VALUE"
        ;;
    *)
        exit 2
        ;;
esac
HELPER
chmod 755 "$CHECKPOINT_HELPER"

# Create sudoers file
cat > "$SUDOERS_FILE" << EOF
# OpenEMS Network Management
# Allows passwordless access to network configuration commands
# Generated by setup-network-sudoers.sh

# NetworkManager (nmcli) - for network configuration
$OPENEMS_USER ALL=(ALL) NOPASSWD: /usr/bin/nmcli

# Restricted helper - for NetworkManager checkpoint create/confirm/rollback
$OPENEMS_USER ALL=(root) NOPASSWD: $CHECKPOINT_HELPER

EOF

# Set correct permissions
chmod 440 "$SUDOERS_FILE"

# Validate sudoers syntax
if visudo -c -f "$SUDOERS_FILE" &>/dev/null; then
    echo "✓ Sudoers file created: $SUDOERS_FILE"
    echo ""
    echo "Granted permissions:"
echo "  - nmcli (NetworkManager CLI)"
echo "  - openems-network-checkpoint (restricted NetworkManager transactions)"
echo ""
else
    echo "ERROR: Invalid sudoers syntax. Removing file..."
    rm -f "$SUDOERS_FILE"
    exit 1
fi

# Verify
echo "Verifying configuration..."
if sudo -u "$OPENEMS_USER" sudo -n nmcli general status &>/dev/null 2>&1; then
    echo "✓ nmcli access verified"
else
    echo "! nmcli verification skipped (user may not have shell access)"
fi

echo ""
echo "=============================================="
echo "Setup Complete!"
echo "=============================================="
echo ""
echo "The following commands can now be run by '$OPENEMS_USER' without password:"
echo "  - sudo nmcli ..."
echo "  - sudo $CHECKPOINT_HELPER ..."
echo ""
echo "To remove these permissions, delete: $SUDOERS_FILE"
echo ""
